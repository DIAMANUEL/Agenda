create table if not exists public.class_events (
 id bigint generated by default as identity primary key,
 type text not null check(type in ('exam','task','other')),
 event_date date not null,
 event_time time,
 title text not null,
 subject text not null,
 description text not null default '',
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.class_events enable row level security;
alter table public.admin_users enable row level security;
create policy "Public can read events" on public.class_events for select to anon,authenticated using(true);
create policy "Admins insert events" on public.class_events for insert to authenticated
 with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "Admins update events" on public.class_events for update to authenticated
 using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()))
 with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "Admins delete events" on public.class_events for delete to authenticated
 using(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "Admins read own admin row" on public.admin_users for select to authenticated using(user_id=auth.uid());
